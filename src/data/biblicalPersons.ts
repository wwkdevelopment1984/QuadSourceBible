export function findPreloadedPerson(query: string): BiblicalPerson | undefined {
  const q = query.trim().toLowerCase();
  return PRELOADED_PERSONS.find(
    (p) =>
      p.englishName.toLowerCase() === q ||
      p.chineseName.includes(query.trim()) ||
      query.trim().includes(p.chineseName) ||
      p.englishName.toLowerCase().includes(q)
  );
}
